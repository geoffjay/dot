//! `dot propose`: publish local changes upstream as a GitHub issue.

use std::collections::BTreeMap;

use anyhow::{Context, Result};

const REPO: &str = "geoffjay/dot";
const LABEL: &str = "proposal";
const REDACT_KEYS: [&str; 4] = ["token", "password", "secret", "key"];

pub(crate) fn run(module_filter: &[String], dry_run: bool) -> Result<()> {
    let (home, config, facts, modules) = crate::load_context(module_filter)?;
    let manifest = dot_core::state::Manifest::load(&home)?;
    let version = env!("CARGO_PKG_VERSION");

    // Only propose for managed files: the diff of interest is on-disk
    // content vs. what the current binary + config would render.
    let mut sections: BTreeMap<String, Vec<(String, String)>> = BTreeMap::new();
    let mut total = 0;

    for module in &modules {
        let rendered = dot_core::render::render_module(
            module,
            &config,
            &facts,
            &home,
            Some(&home.join(".config/dot")),
            &[],
            version,
        )?;

        // Sensitive targets never leave the host.
        let sensitive: Vec<String> = module
            .files_for_os(&facts.os)
            .values()
            .filter(|t| module.sensitive.iter().any(|s| s == t.path()))
            .map(|t| t.path().to_string())
            .collect();

        for r in rendered {
            if !manifest.contains(&r.target) {
                continue; // not dot-managed on this host: not our drift
            }
            if sensitive.iter().any(|s| {
                *s == format!(
                    "~/{}",
                    r.target
                        .strip_prefix(&home)
                        .ok()
                        .and_then(|p| p.to_str())
                        .unwrap_or("")
                        .replace('\\', "/")
                )
            }) {
                continue;
            }

            let on_disk = std::fs::read_to_string(&r.target);
            let differs = match &on_disk {
                Ok(disk) => *disk != r.content,
                Err(_) => true, // vanished: worth reporting
            };
            if !differs {
                continue;
            }

            let diff =
                dot_core::diff::unified_hunks(&r.target, on_disk.as_deref().ok(), &r.content);
            let entry = (format!("{} ({})", r.target.display(), r.module), diff);
            sections.entry(module.name.clone()).or_default().push(entry);
            total += 1;
        }
    }

    if total == 0 {
        println!("no local changes to propose");
        return Ok(());
    }

    let title = if module_filter.len() == 1 {
        format!("proposal: {} config changes", module_filter[0])
    } else {
        "proposal: dot config changes".to_string()
    };
    let body = render_issue_body(&facts, &config, module_filter, &sections, version);

    if dry_run {
        println!("--- dry run: would open the following issue on {REPO} ---");
        println!("title: {title}");
        println!("{body}");
        return Ok(());
    }

    create_issue(&title, &body)?;
    println!("opened issue on {REPO} covering {total} changed file(s)");
    Ok(())
}

fn render_issue_body(
    facts: &dot_core::HostFacts,
    config: &dot_core::Config,
    module_filter: &[String],
    sections: &BTreeMap<String, Vec<(String, String)>>,
    version: &str,
) -> String {
    let mut out = String::new();
    out.push_str("Proposed changes generated by `dot propose`.\n\n");

    out.push_str("## Host\n\n");
    out.push_str("| field | value |\n|---|---|\n");
    out.push_str(&format!("| os | {} |\n", facts.os));
    out.push_str(&format!("| distro | {} |\n", facts.distro));
    out.push_str(&format!("| arch | {} |\n", facts.arch));
    out.push_str(&format!("| hostname | {} |\n", facts.hostname));
    out.push_str(&format!("| dot | {version} |\n"));

    out.push_str("## Config\n\n");
    for module in module_filter {
        let settings = config.module_settings(module, &facts.hostname, &[]);
        out.push_str(&format!("`[{module}]`\n\n```toml\n"));
        out.push_str(&redact(
            &toml::to_string_pretty(&settings).unwrap_or_default(),
        ));
        out.push_str("\n```\n\n");
    }

    out.push_str("## Diffs\n\n");
    for (module, entries) in sections {
        out.push_str(&format!("### {module}\n\n"));
        for (target, diff) in entries {
            out.push_str(&format!("#### {target}\n\n```diff\n{diff}```\n\n"));
        }
    }
    out
}

/// Replace values of sensitive-looking keys with ***.
fn redact(toml: &str) -> String {
    toml.lines()
        .map(|line| {
            let lower = line.to_lowercase();
            if REDACT_KEYS.iter().any(|k| lower.contains(k)) && line.contains('=') {
                if let Some((key, _)) = line.split_once('=') {
                    return format!("{key}= \"***\"");
                }
            }
            line.to_string()
        })
        .collect::<Vec<_>>()
        .join("\n")
}

fn create_issue(title: &str, body: &str) -> Result<()> {
    // Prefer gh: it reuses the host's existing auth.
    if which::which("gh").is_ok() {
        let status = std::process::Command::new("gh")
            .args([
                "issue", "create", "--repo", REPO, "--label", LABEL, "--title", title, "--body",
                body,
            ])
            .status()
            .context("running gh issue create")?;
        if status.success() {
            return Ok(());
        }
        eprintln!("dot: gh issue create failed; falling back to the API");
    }

    let token = std::env::var("GITHUB_TOKEN").context("GITHUB_TOKEN not set and gh unavailable")?;
    let client = reqwest::blocking::Client::builder()
        .user_agent(concat!("dot/", env!("CARGO_PKG_VERSION")))
        .build()?;
    let url = format!("https://api.github.com/repos/{REPO}/issues");
    let response = client
        .post(&url)
        .header("Authorization", format!("Bearer {token}"))
        .header("Accept", "application/vnd.github+json")
        .json(&serde_json::json!({
            "title": title,
            "body": body,
            "labels": [LABEL],
        }))
        .send()?;
    let status = response.status();
    if !status.is_success() {
        anyhow::bail!("GitHub API returned {status}");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn redact_hides_sensitive_values() {
        let input = "name = \"gh\"\ntoken = \"abc123\"\napi_key = \"zzz\"\ntheme = \"nord\"\n";
        let out = redact(input);
        assert!(out.contains("token = \"***\""));
        assert!(out.contains("api_key = \"***\""));
        assert!(out.contains("theme = \"nord\""));
        assert!(!out.contains("abc123"));
        assert!(!out.contains("zzz"));
    }
}
